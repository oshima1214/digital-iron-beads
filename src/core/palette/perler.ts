const familyOf = (code: string): BeadFamily => {
  const f = FAMILIES.find((x) => x.codes.includes(code));
  if (!f) throw new Error(`no family for bead ${code}`);
  return f.id;
};

const make = (list: [string, string, Rgb][], start: number, group: Bead['group']) =>
  list.map(([code, name, rgb], i): Bead => ({ index: start + i, code, name, rgb, group, family: familyOf(code) }));

/** 全64色。番号 = 配列の位置 + 1 */
export const PALETTE: readonly Bead[] = [...make(BASIC, 1, 'basic'), ...make(EXTENDED, 17, 'extended'), ...make(MORE, 33, 'more')];
/** 64色にする前からある 32色（1〜32） */
export const PERLER32: readonly Bead[] = PALETTE.slice(0, 32);

export const BASIC16: readonly number[] = PERLER32.filter((b) => b.group === 'basic').map((b) => b.index);
/** 元のアプリの基本16色の先頭8色（しろ・きいろ・あか・ピンク・あお・みずいろ・みどり・くろ） */
export const BASIC8: readonly number[] = BASIC16.slice(0, 8);
export const ALL32: readonly number[] = PERLER32.map((b) => b.index);
export const ALL64: readonly number[] = PALETTE.map((b) => b.index);

/** 使うビーズの組み合わせ → ビーズの番号。owned は手持ち（重なり・範囲外を除いて番号順）。original は空。 */
export function beadsForSet(set: BeadSet, owned: readonly number[]): number[] {
  switch (set) {
    case 'original':
      return [];
    case '8':
      return [...BASIC8];
    case '16':
      return [...BASIC16];
    case '32':
      return [...ALL32];
    case 'owned':
      return [...new Set(owned)].filter((i) => Number.isInteger(i) && i >= 1 && i <= PALETTE.length).sort((a, b) => a - b);
  }
}

/** 番号の一覧から組み合わせを推測する（使うビーズの組み合わせを保存していなかった古い作品用） */
export function setOfBeads(list: readonly number[]): Exclude<BeadSet, 'original'> {
  const key = (l: readonly number[]) => [...l].sort((a, b) => a - b).join();
  const k = key(list);
  if (k === key(BASIC8)) return '8';
  if (k === key(BASIC16)) return '16';
  if (k === key(ALL32)) return '32';
  return 'owned';
}

export function beadByIndex(i: number): Bead {
  const b = PALETTE[i - 1];
  if (!b || b.index !== i) throw new RangeError(`bead index out of range: ${i}`);
  return b;
}
